#!/usr/bin/env python3
"""Write <system>/RESULTS.md: one row per finished case (verdict, time, tokens, cost) and totals.

Usage: results.py <system>
Numbers come from summarize.py (the Total row of each run's summary.md, retries included).
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path("/bulk/specula-adhoc")


def money(s: str) -> float:
    m = re.search(r"\$([\d.]+)", s or "")
    return float(m.group(1)) if m else 0.0


def tokens(s: str) -> tuple[float, float]:
    m = re.search(r"([\d.]+)M total \(([\d.]+)M cached\)", s or "")
    return (float(m.group(1)), float(m.group(2))) if m else (0.0, 0.0)


def minutes(s: str) -> int:
    h = re.search(r"(\d+)h", s or "")
    m = re.search(r"(\d+)m", s or "")
    return (int(h.group(1)) if h else 0) * 60 + (int(m.group(1)) if m else 0)



def main() -> None:
    system = sys.argv[1]
    rows = json.loads(subprocess.run([sys.executable, str(ROOT / "summarize.py"), system],
                                     capture_output=True, text=True, check=True).stdout)
    done = [r for r in rows if r.get("state") == "exit 0" and r.get("specula") not in (None, "", "no result yet")]
    out = [f"# {system}: finished cases ({len(done)} of {len(rows)})", "",
           "Regenerated by `tools/results.py` after each finished run. Time, tokens and cost are the `Total` row of the "
           "run's `summary.md` (every session and retry included); wall time is the case log's first start to last finish "
           "(paused runs: see NOTES.md).", "",
           "| case | Specula verdict | mechanism | finding | wall | runtime | usage-limit waits (time) | tokens (cached) | cost |",
           "|---|---|---|---|---|---|---:|---|---:|"]
    tc = tt = tcached = 0.0
    wall = rt = 0
    for r in done:
        out.append(f"| {r['case']} | {r['specula']} | {r['mechanism']} | {r['finding'] or '-'} | "
                   f"{r['wall']} | {r['runtime']} | {r['waits']} ({r['wait_time']}) | {r['tokens']} | {r['cost']} |")
        tc += money(r["cost"]); t, c = tokens(r["tokens"]); tt += t; tcached += c
        wall += minutes(r["wall"]); rt += minutes(r["runtime"])
    out += ["", f"**Totals ({len(done)} runs):** cost ${tc:.2f}; tokens {tt:.1f}M ({tcached:.1f}M cached); "
            f"wall {wall // 60}h{wall % 60:02d}m; runtime {rt // 60}h{rt % 60:02d}m.", ""]
    phases = [f"- {r['case']}: {r['phases']}" for r in done]
    out += ["Per-phase runtime and cost:", ""] + phases + [""]
    (ROOT / system / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out[:8 + len(done)] + out[8 + len(done):10 + len(done)]))


if __name__ == "__main__":
    main()
